// Generates src/styles/ds-v2-tokens.css: the DS 2.0 token set from
// @abgov/design-tokens@2.x (installed under the "design-tokens-v2" alias),
// scoped to `.goa-ds-v2` instead of `:root`.
//
// DS 1.0 and DS 2.0 share token names but not values (e.g. --goa-border-radius-m
// is 0.25rem in v1, 0.5rem in v2). Loading v2 at :root would restyle every v1
// prototype, so v2 prototypes opt in by carrying the `goa-ds-v2` class on their
// host element. Custom properties inherit into shadow roots, so every goab-*
// component inside picks up the v2 values.
//
// Runs automatically before `npm run build` / `npm start`; the output is also
// committed so `npx ng serve` works without running the script first.
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { createRequire } from 'node:module';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const require = createRequire(import.meta.url);
const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const pkg = require('design-tokens-v2/package.json');
const source = readFileSync(require.resolve('design-tokens-v2/dist/tokens.css'), 'utf8');

const rootBlocks = source.match(/:root\s*\{/g) ?? [];
if (rootBlocks.length !== 1) {
  throw new Error(`Expected exactly one :root block in design-tokens-v2, found ${rootBlocks.length}. Check the new format.`);
}

const scoped = source.replace(/:root\s*\{/, '.goa-ds-v2 {');

const out = `/* GENERATED by scripts/build-ds-v2-tokens.mjs from @abgov/design-tokens@${pkg.version}. Do not edit. */
${scoped}
/* Text outside shadow DOM (headings, body copy) inherits the v2 typeface too. */
.goa-ds-v2 {
  font-family: var(--goa-font-family-sans);
  color: var(--goa-color-text-default);
}
`;

const target = resolve(root, 'src/styles/ds-v2-tokens.css');
mkdirSync(dirname(target), { recursive: true });
writeFileSync(target, out);
console.log(`ds-v2-tokens.css generated from @abgov/design-tokens@${pkg.version}`);
